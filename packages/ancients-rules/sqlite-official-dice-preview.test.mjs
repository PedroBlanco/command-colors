import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync, rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {openOfficialAncientsRangedPreviewLab,
  openGuardedAncientsReservationLab} from './sqlite-guarded-reservation.mjs';
import {ANCIENTS_BATTLE_DIE_FACES} from './battle-dice.mjs';
import {OFFICIAL_PREVIEW_DICE_PLAN, SYNTHETIC_DICE_PLAN,
  LAB_DIE_FACES} from './dice-plan.mjs';

const MATCH='123e4567-e89b-42d3-a456-426614174000';
const state=()=>({schemaVersion:1,ruleset:'ancients-base-3e-2009',status:'ACTIVE',
  turn:'A',phase:'COMBAT',revision:4,orderedUnitIds:['a1'],
  resolvedBattleUnitIds:[],movedStepsByUnit:{a1:0},pendingCombat:null,pendingDecision:null});
const board=(targetType='HEAVY_INFANTRY',terrain=[])=>({
  units:[{id:'a1',side:'A',type:'LIGHT_BOW_INFANTRY',col:2,row:4},
    {id:'b1',side:'B',type:targetType,col:5,row:4}],leaders:[],terrain});
const reserveInput=(more={})=>({matchId:MATCH,sessionUserId:'alice',attackerId:'a1',
  targetId:'b1',expectedRevision:4,idempotencyKey:'official_reserve_01',...more});
const stageInput=(reservationId,more={})=>({matchId:MATCH,sessionUserId:'alice',reservationId,
  expectedRevision:5,idempotencyKey:'official_stage_01',mode:'PHYSICAL',
  declaredFaces:['HEAVY','FLAG'],...more});
const cancelInput=(reservationId,more={})=>({matchId:MATCH,sessionUserId:'alice',reservationId,
  expectedRevision:5,idempotencyKey:'official_cancel_01',...more});
function fixture(fn,{targetType='HEAVY_INFANTRY',terrain=[]}={}) {
  const folder=mkdtempSync(join(tmpdir(),'ccw-official-preview-'));
  const file=join(folder,'lab.sqlite');const connections=[];
  const openOfficial=()=>{const s=openOfficialAncientsRangedPreviewLab({file});connections.push(s);return s;};
  const openSynthetic=()=>{const s=openGuardedAncientsReservationLab({file});connections.push(s);return s;};
  try {const store=openOfficial();store.seedFixture({matchId:MATCH,ownerId:'alice',guestId:'bob',
    turnState:state(),board:board(targetType,terrain)});
    return fn({store,openOfficial,openSynthetic});
  } finally {for(const s of connections.reverse())try{s.close();}catch{}
    rmSync(folder,{recursive:true,force:true,maxRetries:20,retryDelay:100});}
}
const reserve=s=>{const r=s.reserve(reserveInput());assert.equal(r.code,'SCREENING_RESERVED');return r;};

test('official preview plan is versioned, six-face and target type comes from server board',()=>fixture(({store})=>{
  reserve(store);
  const plan=store.inspectFixture({matchId:MATCH,sessionUserId:'alice'}).turnState.pendingCombat.dicePlan;
  assert.equal(plan.schemaVersion,1);
  assert.equal(plan.kind,OFFICIAL_PREVIEW_DICE_PLAN);
  assert.equal(plan.ruleset,'ancients-base-3e-2009');
  assert.equal(plan.targetUnitType,'HEAVY_INFANTRY');
  assert.equal(plan.diceCount,2);
  assert.deepEqual(plan.dieFaces,[...ANCIENTS_BATTLE_DIE_FACES]);
}));

test('physical six-face result is stored and interpreted against target, not applied',()=>fixture(({store})=>{
  const r=reserve(store),v=store.stageDice(stageInput(r.reservationId));
  assert.equal(v.code,'DICE_STAGED_OFFICIAL_PREVIEW');
  assert.equal(v.previewOnly,true);assert.equal(v.combatResolved,false);
  assert.equal(v.attackAuthorized,false);
  assert.equal(v.roll.type,'ANCIENTS_BASE_RANGED_DICE_CAPTURED');
  assert.equal(v.roll.verification,'PLAYER_DECLARED');
  assert.deepEqual(v.roll.results,['HEAVY','FLAG']);
  assert.equal(v.interpretation.matchingColorHits,1);
  assert.equal(v.interpretation.flagsPending,1);
  assert.equal(v.interpretation.hitsApplied,false);
  const current=store.inspectFixture({matchId:MATCH,sessionUserId:'bob'}).turnState;
  assert.equal(current.pendingCombat.kind,'RANGED_DICE_STAGED_OFFICIAL_PREVIEW');
  assert.equal(current.pendingCombat.previewInterpretation.combatResolved,false);
  assert.deepEqual(current.resolvedBattleUnitIds,[]);
}));

test('digital six-face roll is generated by server, saved privately and not reversible',()=>fixture(({store})=>{
  const r=reserve(store),v=store.stageDice(stageInput(r.reservationId,{mode:'DIGITAL',declaredFaces:undefined}));
  assert.equal(v.code,'DICE_STAGED_OFFICIAL_PREVIEW');
  assert.equal(v.roll.verification,'SERVER_GENERATED');
  assert.equal(v.roll.results.length,2);
  assert.ok(v.roll.results.every(x=>ANCIENTS_BATTLE_DIE_FACES.includes(x)));
  assert.equal(store.cancel(cancelInput(r.reservationId,{expectedRevision:6})).code,'RESERVATION_NOT_CANCELLABLE');
}));

test('duplicate digital command returns exactly the original random faces after reopening',()=>fixture(({store,openOfficial})=>{
  const r=reserve(store),cmd=stageInput(r.reservationId,{mode:'DIGITAL',declaredFaces:undefined});
  const first=store.stageDice(cmd);store.close();
  const second=openOfficial().stageDice(cmd);
  assert.equal(second.code,'ALREADY_STAGED');
  assert.deepEqual(second.roll,first.roll);
  assert.deepEqual(second.interpretation,first.interpretation);
  assert.equal(second.revision,6);
}));

test('reopening with synthetic mode cannot convert a persisted official preview plan',()=>fixture(({store,openSynthetic})=>{
  const r=reserve(store);store.close();
  const other=openSynthetic(),v=other.stageDice(stageInput(r.reservationId));
  assert.equal(v.code,'DICE_STAGED_OFFICIAL_PREVIEW');
  assert.equal(v.roll.results[0],'HEAVY');
  assert.equal(v.interpretation.matchingColorHits,1);
}));

test('reopening an earlier synthetic reservation does not silently upgrade its plan',()=>fixture(({store,openSynthetic,openOfficial})=>{
  store.close();const synthetic=openSynthetic();
  const r=synthetic.reserve(reserveInput());synthetic.close();
  const other=openOfficial();
  const plan=other.inspectFixture({matchId:MATCH,sessionUserId:'alice'}).turnState.pendingCombat.dicePlan;
  assert.equal(plan.kind,SYNTHETIC_DICE_PLAN);
  assert.deepEqual(plan.dieFaces,[...LAB_DIE_FACES]);
  const v=other.stageDice(stageInput(r.reservationId,{declaredFaces:['RED','BLUE']}));
  assert.equal(v.code,'DICE_STAGED_SYNTHETIC');
  assert.equal(v.roll.type,'DICE_ROLLED_SYNTHETIC');
}));

test('unversioned legacy synthetic reservation remains usable after reopening official wrapper',()=>fixture(({store,openSynthetic,openOfficial})=>{
  store.close();const old=openSynthetic(),r=old.reserve(reserveInput());
  const db=old.unsafeTestDatabase(),entry=db.prepare('SELECT turn_json FROM lab_matches WHERE id=?').get(MATCH);
  const oldTurn=JSON.parse(entry.turn_json);
  oldTurn.pendingCombat.dicePlan={diceCount:2,dieFaces:[...LAB_DIE_FACES]};
  db.prepare('UPDATE lab_matches SET turn_json=? WHERE id=?').run(JSON.stringify(oldTurn),MATCH);
  old.close();
  const newer=openOfficial();
  const stage=newer.stageDice(stageInput(r.reservationId,{declaredFaces:['RED','BLUE']}));
  assert.equal(stage.code,'DICE_STAGED_SYNTHETIC');
  assert.deepEqual(stage.roll.results,['RED','BLUE']);
  assert.equal(newer.inspectFixture({matchId:MATCH,sessionUserId:'alice'}).turnState.pendingCombat.previewInterpretation,undefined);
}));

