test('idempotency refuses second key, changed mode or revision',()=>fixture(({store})=>{
  const r=reserve(store),cmd=stageInput(r.reservationId);
  assert.equal(store.stageDice(cmd).code,'DICE_STAGED_OFFICIAL_PREVIEW');
  assert.equal(store.stageDice({...cmd,mode:'DIGITAL',declaredFaces:undefined}).code,'IDEMPOTENCY_KEY_REUSED');
  assert.equal(store.stageDice({...cmd,expectedRevision:6}).code,'IDEMPOTENCY_KEY_REUSED');
  assert.equal(store.stageDice({...cmd,expectedRevision:6,idempotencyKey:'official_stage_02'}).code,'RESERVATION_NOT_STAGEABLE');
}));

test('other player and stranger cannot stage official preview dice',()=>fixture(({store})=>{
  const r=reserve(store);
  assert.equal(store.stageDice(stageInput(r.reservationId,{sessionUserId:'bob'})).code,'RESERVATION_NOT_STAGEABLE');
  assert.equal(store.stageDice(stageInput(r.reservationId,{sessionUserId:'mallory'})).code,'NOT_FOUND');
  assert.equal(store.inspectFixture({matchId:MATCH,sessionUserId:'bob'}).revision,5);
}));

test('rollback after event failure leaves no staged official dice or key',()=>fixture(({store})=>{
  const r=reserve(store),db=store.unsafeTestDatabase(),cmd=stageInput(r.reservationId);
  db.exec("CREATE TRIGGER abort_stage BEFORE INSERT ON lab_events BEGIN SELECT RAISE(ABORT,'STAGE_TEST_IO_ERROR'); END");
  assert.throws(()=>store.stageDice(cmd),/STAGE_TEST_IO_ERROR/);
  assert.equal(store.inspectFixture({matchId:MATCH,sessionUserId:'alice'}).revision,5);
  assert.equal(store.inspectFixture({matchId:MATCH,sessionUserId:'alice'}).turnState.pendingCombat.stagedDice,undefined);
  assert.equal(db.prepare('SELECT COUNT(*) AS count FROM lab_commands').get().count,1);
  db.exec('DROP TRIGGER abort_stage');
  assert.equal(store.stageDice(cmd).code,'DICE_STAGED_OFFICIAL_PREVIEW');
}));

test('public events omit six-face results, unit ids, roll ids and their interpretation',()=>fixture(({store})=>{
  const r=reserve(store),v=store.stageDice(stageInput(r.reservationId));
  const events=store.inspectFixture({matchId:MATCH,sessionUserId:'bob'}).events;
  assert.deepEqual(events[1],{sequence:6,type:'RANGED_DICE_STAGED_OFFICIAL_PREVIEW',side:'A',source:'PHYSICAL',diceCount:2});
  assert.equal(JSON.stringify(events).includes(r.reservationId),false);
  for(const key of ['matchingColorHits','flagsPending','results','attackerId','targetId'])
    assert.equal(JSON.stringify(events).includes(key),false);
  assert.equal(v.combatResolved,false);
}));

test('invalid plan schema is refused, never silently treated as synthetic or official',()=>fixture(({store})=>{
  const r=reserve(store),db=store.unsafeTestDatabase();
  const raw=db.prepare('SELECT turn_json FROM lab_matches WHERE id=?').get(MATCH);
  const turnState=JSON.parse(raw.turn_json);
  turnState.pendingCombat.dicePlan.schemaVersion=2;
  db.prepare('UPDATE lab_matches SET turn_json=? WHERE id=?').run(JSON.stringify(turnState),MATCH);
  assert.equal(store.stageDice(stageInput(r.reservationId)).code,'DICE_PLAN_UNAVAILABLE');
  assert.equal(store.inspectFixture({matchId:MATCH,sessionUserId:'alice'}).revision,5);
}));

test('cancel official screening before any dice and allow new reservation with fresh revision',()=>fixture(({store})=>{
  const r=reserve(store);
  assert.equal(store.cancel(cancelInput(r.reservationId)).code,'SCREENING_CANCELLED');
  const second=store.reserve(reserveInput({expectedRevision:6,idempotencyKey:'official_reserve_02'}));
  assert.equal(second.code,'SCREENING_RESERVED');assert.equal(second.revision,7);
  assert.equal(store.inspectFixture({matchId:MATCH,sessionUserId:'alice'}).turnState.pendingCombat.dicePlan.kind,
    OFFICIAL_PREVIEW_DICE_PLAN);
}));
